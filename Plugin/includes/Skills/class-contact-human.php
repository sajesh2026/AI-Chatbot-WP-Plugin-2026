<?php
/**
 * Contact Human Skill and Lead Generation.
 *
 * @package AIChatbot\Skills
 */

namespace AIChatbot\Skills;

use AIChatbot\Security\Sanitizer;
use AIChatbot\Email\EmailQueue;

defined( 'ABSPATH' ) || exit;

/**
 * Class ContactHuman.
 */
class ContactHuman {

	/**
	 * Process a public contact form submission.
	 *
	 * @param array $params Request parameters (name, email, phone, company, message, honeypot).
	 * @param int   $agent_id Agent ID.
	 * @return array{success: bool, message: string, lead_id?: int}
	 */
	public static function submit( array $params, int $agent_id = 1 ): array {
		global $wpdb;
		$table_leads = $wpdb->prefix . 'ai_leads';

		// 1. Honeypot check.
		if ( Sanitizer::is_honeypot_triggered( $params ) ) {
			// Silent drop for bots - return standard success message.
			return array(
				'success' => true,
				'message' => __( 'Your message has been received.', 'ai-chatbot' ),
			);
		}

		// 2. Validate required fields.
		$name    = sanitize_text_field( $params['name'] ?? '' );
		$email   = sanitize_email( $params['email'] ?? '' );
		$phone   = sanitize_text_field( $params['phone'] ?? '' );
		$company = sanitize_text_field( $params['company'] ?? '' );
		$message = sanitize_textarea_field( $params['message'] ?? '' );

		if ( empty( $name ) || empty( $email ) || ! is_email( $email ) ) {
			return array(
				'success' => false,
				'message' => __( 'Please provide a valid name and email address.', 'ai-chatbot' ),
			);
		}

		// 3. Save lead to wp_ai_leads.
		$conversation_id = ! empty( $params['conversation_id'] ) ? (int) $params['conversation_id'] : null;

		$inserted = $wpdb->insert(
			$table_leads,
			array(
				'agent_id'        => $agent_id,
				'conversation_id' => $conversation_id,
				'name'            => $name,
				'email'           => $email,
				'phone'           => $phone,
				'company'         => $company,
				'message'         => $message,
				'status'          => 'new',
				'created_at'      => current_time( 'mysql' ),
			),
			array( '%d', '%d', '%s', '%s', '%s', '%s', '%s', '%s', '%s' )
		);

		$lead_id = $inserted ? (int) $wpdb->insert_id : 0;

		// 4. Trigger Email Notification.
		$config = self::get_config( $agent_id );

		if ( ! empty( $config['send_email'] ) ) {
			$to = ! empty( $config['notification_recipient'] ) ? $config['notification_recipient'] : get_option( 'admin_email' );
			$site_name = get_bloginfo( 'name' );

			$subject = sprintf( __( '[%s] New Lead from AI Chatbot: %s', 'ai-chatbot' ), $site_name, $name );

			$safe_name    = esc_html( $name );
			$safe_email   = esc_html( $email );
			$safe_phone   = esc_html( $phone ?: 'Not provided' );
			$safe_company = esc_html( $company ?: 'Not provided' );
			$safe_message = nl2br( esc_html( $message ) );

			$html = <<<HTML
<h2>New Lead / Contact Request</h2>
<p>A website visitor submitted the "Contact Human" form on your AI Chatbot:</p>
<table style="width:100%; border-collapse:collapse; margin-top:15px; font-family:sans-serif;">
  <tr><td style="padding:8px; border:1px solid #ddd; width:120px;"><strong>Name:</strong></td><td style="padding:8px; border:1px solid #ddd;">{$safe_name}</td></tr>
  <tr><td style="padding:8px; border:1px solid #ddd;"><strong>Email:</strong></td><td style="padding:8px; border:1px solid #ddd;"><a href="mailto:{$safe_email}">{$safe_email}</a></td></tr>
  <tr><td style="padding:8px; border:1px solid #ddd;"><strong>Phone:</strong></td><td style="padding:8px; border:1px solid #ddd;">{$safe_phone}</td></tr>
  <tr><td style="padding:8px; border:1px solid #ddd;"><strong>Company:</strong></td><td style="padding:8px; border:1px solid #ddd;">{$safe_company}</td></tr>
  <tr><td style="padding:8px; border:1px solid #ddd;"><strong>Message:</strong></td><td style="padding:8px; border:1px solid #ddd;">{$safe_message}</td></tr>
</table>
<p style="margin-top:20px; font-size:13px; color:#666;">Generated by AI Chatbot on {$site_name}.</p>
HTML;

			$idempotency_key = "lead-notification/{$lead_id}";

			EmailQueue::queue(
				$to,
				$subject,
				$html,
				array( 'reply_to' => $email ),
				$idempotency_key,
				true
			);
		}

		$confirmation = ! empty( $config['confirmation_message'] )
			? $config['confirmation_message']
			: __( 'Thanks! Your request has been received. Our team will contact you shortly.', 'ai-chatbot' );

		return array(
			'success' => true,
			'message' => $confirmation,
			'lead_id' => $lead_id,
		);
	}

	/**
	 * Get contact human configuration for an agent.
	 *
	 * @param int $agent_id Agent ID.
	 * @return array
	 */
	public static function get_config( int $agent_id = 1 ): array {
		global $wpdb;
		$table = $wpdb->prefix . 'ai_settings';

		$rows = $wpdb->get_results(
			$wpdb->prepare(
				"SELECT setting_key, setting_value FROM {$table} WHERE setting_group = %s AND agent_id = %d",
				'skills_contact',
				$agent_id
			),
			ARRAY_A
		);

		$config = array(
			'enabled'                => true,
			'send_email'             => true,
			'notification_recipient' => \AIChatbot\Settings::get_support_email( $agent_id ) ?: (string) get_option( 'admin_email' ),
			'fields'                 => array(
				'name'    => array( 'enabled' => true, 'required' => true ),
				'email'   => array( 'enabled' => true, 'required' => true ),
				'phone'   => array( 'enabled' => true, 'required' => false ),
				'company' => array( 'enabled' => true, 'required' => false ),
				'message' => array( 'enabled' => true, 'required' => true ),
			),
			'confirmation_message'   => __( 'Thanks! Your request has been received. Our team will contact you shortly.', 'ai-chatbot' ),
		);

		if ( ! empty( $rows ) ) {
			foreach ( $rows as $r ) {
				$val = $r['setting_value'];
				if ( 'fields' === $r['setting_key'] ) {
					$config['fields'] = json_decode( $val, true ) ?: $config['fields'];
				} elseif ( in_array( $val, array( '1', '0', 'true', 'false' ), true ) ) {
					$config[ $r['setting_key'] ] = in_array( $val, array( '1', 'true' ), true );
				} else {
					$config[ $r['setting_key'] ] = $val;
				}
			}
		}

		return $config;
	}
}
